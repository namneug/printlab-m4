const hintWord = (n: number): string => `ขอคำใบ้ได้ ${n} ครั้ง`;

function section(num: number, id: string, title: string, ...children: (Node | string | null)[]): HTMLElement {
  return el('section', { class: 'hsec', id }, el('div', { class: 'hsec__head' }, el('span', { class: 'hsec__num', text: String(num) }), el('h2', { text: title })), ...children);
}
function li(...c: (Node | string)[]): HTMLElement {
  return el('li', {}, ...c);
}
function part(cls: string, title: string, desc: string): HTMLElement {
  return el('div', { class: `screen-part ${cls}` }, el('h3', { text: title }), el('p', { text: desc }));
}
function levelCard(id: string, must: string[], pass: string, tips: string[]): HTMLElement {
  const m = lv(id);
  if (!m) return el('div');
  return el('article', { class: 'lvl', id: `lvl-${id}` },
    el('div', { class: 'lvl__head' }, el('span', { class: 'lvl__num', text: String(m.number).padStart(2, '0') }), el('h3', { class: 'lvl__title', text: m.title }), el('span', { class: 'lvl__meta', text: `≈ ${m.estimatedMinutes} นาที · ${hintWord(m.hintLevelMax)} · ${m.indicators.join(', ')}` })),
    el('dl', {},
      el('dt', { text: 'ต้องทำ' }), el('dd', {}, el('ul', {}, ...must.map((t) => el('li', { text: t })))),
      el('dt', { text: 'ผ่านเมื่อ' }), el('dd', { text: pass }),
      el('dt', { text: 'เคล็ดลับ' }), el('dd', {}, el('ul', {}, ...tips.map((t) => el('li', { text: t })))),
    ),
  );
}

